-- Овнер — участник, которого видно только админу отдельным отчётом. В зарплате
-- и в командной статистике он не участвует: флаг нужен, чтобы тянуть цифры по
-- его кабинетам, не смешивая их с командой баеров.
ALTER TABLE "Buyer" ADD COLUMN "owner" BOOLEAN NOT NULL DEFAULT false;

-- Овнеры команды — SKO и MPR. Помечаем сразу, чтобы их статистика ушла в свой
-- лист, а не в командный. Если такого хендла нет — строка просто ничего не
-- тронет.
UPDATE "Buyer" SET "owner" = true WHERE "handle" IN ('SKO', 'MPR');
