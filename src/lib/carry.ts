/**
 * Хвост минуса: неперекрытый убыток тянется в следующие недели.
 *
 * Правило простое и одностороннее. Закрыл неделю в плюс — всё, неделя
 * посчитана и забыта. Закрыл в минус — этот минус не исчезает: он переезжает в
 * следующую неделю и должен быть перекрыт своим же плюсом, прежде чем начнёт
 * капать процент. Пока хвост не погашен, процента нет.
 *
 * Плюс НЕ копится: перекрыл хвост — остаток идёт в базу этой недели, а не
 * складывается в запас на будущие просадки. Иначе это была бы уже не зарплата
 * за период, а общий счёт за всё время.
 *
 * Живёт отдельным файлом и ничего не знает про базу: цена ошибки здесь —
 * неверная зарплата, а такое хочется уметь прогнать отдельно.
 */

/** База одной недели: профит за вычетом расходников, если они заряжены. */
export type WeekBase = {
  /** Понедельник недели, YYYY-MM-DD — по нему же недели и упорядочены. */
  weekKey: string;
  baseCents: number;
  /** Оклад, выданный за эту неделю. На МИНУСОВОЙ неделе он уходит в долг вместе
   *  с минусом: баер отбивает и свой минус, и выданный оклад из будущего плюса.
   *  На плюсовой неделе не влияет. */
  okladCents?: number;
};

/**
 * Сколько минуса человек притащил из прошлых недель. Всегда ≥ 0: ноль значит
 * «чист», положительное — столько нужно перекрыть до первого процента.
 *
 * Недели складываем по порядку и на каждом шаге обрезаем баланс сверху нулём:
 * плюсовая неделя гасит хвост и не оставляет запаса, минусовая — добавляет.
 */
export function carriedDebt(weeks: WeekBase[]): number {
  let balance = 0; // ≤ 0: это долг, а не накопления
  for (const week of [...weeks].sort((a, b) => (a.weekKey < b.weekKey ? -1 : 1))) {
    // Плюсовая неделя гасит долг своей базой. Минусовая добавляет и минус базы,
    // и выданный оклад — его баер тоже отбивает будущим плюсом.
    const delta = week.baseCents >= 0 ? week.baseCents : week.baseCents - (week.okladCents ?? 0);
    balance = Math.min(0, balance + delta);
  }
  // max гасит «-0», который иначе печатается в отчёте минусом на пустом месте.
  return Math.max(0, -balance);
}

/** Как хвост раскладывается внутри одной недели. */
export type CarrySplit = {
  /** Пришло долгом с прошлых недель. */
  inCents: number;
  /** Сколько из него перекрыли этой неделей. */
  coveredCents: number;
  /** Что осталось и уедет дальше — вместе с новым минусом, если он есть. */
  outCents: number;
};

/**
 * Развилка на одну неделю: сколько долга погасили и сколько поехало дальше.
 * `grossBaseCents` — база недели до вычета хвоста.
 */
export function splitCarry(grossBaseCents: number, inCents: number): CarrySplit {
  const carried = Math.max(0, inCents);
  return {
    inCents: carried,
    coveredCents: Math.min(carried, Math.max(0, grossBaseCents)),
    // Минусовая неделя не только не гасит долг, но и добавляет свой:
    // carried − (−300) = carried + 300.
    outCents: Math.max(0, carried - grossBaseCents),
  };
}
