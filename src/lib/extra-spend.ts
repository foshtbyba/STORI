/**
 * Доп. расходы — то, что не приезжает из Brocard, а заводится руками.
 *
 * Сейчас это агентские кабинеты: их пополняют мимо карт Brocard, синхронизация
 * о них не знает вовсе, а комиссия там своя — 6%, и никаких других сверху не
 * накручивается.
 *
 * Поэтому такой расход живёт отдельной строкой дня со своим источником.
 * Отдельная строка решает сразу две задачи:
 *
 *  1. Синхронизация ходит только по строкам с источником «Facebook» — агентскую
 *     она не видит и переписать не может. Ровно то, что нужно: цифра ручная.
 *  2. Во все итоги — профит, ROI, зарплату, гору, «за всё время» — она попадает
 *     сама, потому что это обычный отчёт дня. Ничего досчитывать отдельно не
 *     нужно, и разъехаться цифрам негде.
 */

