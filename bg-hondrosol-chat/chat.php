function isValidBGPhone($phone) {
    $clean = preg_replace('/[\s\-\(\)\.]+/', '', $phone);
    if (preg_match('/^(\+?359|00359)\d{8,9}$/', $clean)) return true;
    if (preg_match('/^0[1-9]\d{7,8}$/', $clean)) return true;
    return false;
}

function extractPhone($text) {
    $clean = preg_replace('/[\s\-\(\)\.]+/', '', $text);
    if (preg_match('/(\+?359\d{8,9}|00359\d{8,9}|0[1-9]\d{7,8})/', $clean, $m)) {
        return $m[1];
    }
    return $clean;
}

