// ===== ОБРАБОТКА ЗАПРОСА =====
$input = json_decode(file_get_contents('php://input'), true);
if (!$input) {
    echo json_encode(['ok' => false, 'error' => 'invalid request']);
    exit;
}

$op = $input['op'] ?? '';
$history = $input['history'] ?? [];
$text = $input['text'] ?? '';

// Собираем историю как текст
$chatLog = '';
foreach ($history as $msg) {
    if (isset($msg['role']) && isset($msg['content'])) {
        $clean = preg_replace('#<<[^>]*>>#u', '', $msg['content']);
        $label = ($msg['role'] === 'user') ? 'Пациент' : 'Д-р Димитров';
        $chatLog .= $label . ': ' . trim($clean) . "\n";
    }
}

// Добавляем новое сообщение
if ($op === 'say' && $text) {
    $chatLog .= 'Пациент: ' . $text . "\n";
}

// Собираем prompt для GPT
$userMsg = '';
if ($op === 'start') {
    $userMsg = 'Пациентът отвори чата. Започни разговора — поздрави и попитай къде го боли.';
} else {
    $userMsg = "Ето разговора досега:\n\n" . $chatLog . "\nПРАВИЛА:\n1. Прочети внимателно целия разговор по-горе.\n2. НЕ повтаряй въпрос, който вече си задал. Ако вече си питал за възраст — НЕ питай пак.\n3. Ако пациентът е отговорил с кратък текст (напр. \"31-40\", \"Колене\") — това Е отговор. Приеми го.\n4. Определи на коя стъпка от плана си и задай СЛЕДВАЩИЯ въпрос.\n5. Отговори САМО като д-р Димитров, на български.";
}

$messages = [
    ['role' => 'system', 'content' => $SYSTEM_PROMPT],
    ['role' => 'user', 'content' => $userMsg],
];

// ===== ВЫЗОВ OpenAI API =====
$ch = curl_init('https://api.openai.com/v1/chat/completions');
curl_setopt_array($ch, [
    CURLOPT_RETURNTRANSFER => true,
    CURLOPT_POST => true,
    CURLOPT_HTTPHEADER => [
        'Content-Type: application/json',
        'Authorization: Bearer ' . OPENAI_API_KEY,
    ],
    CURLOPT_POSTFIELDS => json_encode([
        'model' => MODEL,
        'messages' => $messages,
        'temperature' => 0.7,
        'max_tokens' => 1024,
    ]),
    CURLOPT_TIMEOUT => 30,
]);
$response = curl_exec($ch);
$curlErr = curl_error($ch);
$httpCode = curl_getinfo($ch, CURLINFO_HTTP_CODE);
curl_close($ch);

if ($curlErr) {
    echo json_encode(['ok' => false, 'error' => 'curl: ' . $curlErr]);
    exit;
}

if ($httpCode !== 200) {
    echo json_encode(['ok' => false, 'error' => 'API error: HTTP ' . $httpCode]);
    exit;
}

$data = json_decode($response, true);
$reply = $data['choices'][0]['message']['content'] ?? '';

if (!$reply) {
    echo json_encode(['ok' => false, 'error' => 'empty response']);
    exit;
}

// ===== ПАРСИМ ОТВЕТ =====
$buttons = [];
$lead = null;

// Извлекаем кнопки
if (preg_match('#<<(?:BUTTONS|КНОПКИ)>>(.+?)<<\/(?:BUTTONS|КНОПКИ)>>#su', $reply, $m)) {
    $buttons = array_map('trim', explode('|', $m[1]));
    $reply = trim(preg_replace('#<<(?:BUTTONS|КНОПКИ)>>(.+?)<<\/(?:BUTTONS|КНОПКИ)>>#su', '', $reply));
}

// Извлекаем lead
if (preg_match('#<<(?:LEAD|ЛИД)>>(.+?)<<\/(?:LEAD|ЛИД)>>#su', $reply, $m)) {
    $parts = explode('|', $m[1]);
    $lead = [];
    foreach ($parts as $p) {
        list($k, $v) = explode('=', $p, 2);
        $lead[trim($k)] = trim($v);
    }
    $reply = trim(preg_replace('#<<(?:LEAD|ЛИД)>>(.+?)<<\/(?:LEAD|ЛИД)>>#su', '', $reply));
}

// Разбиваем на несколько пузырей по двойному переносу
$msgs = array_values(array_filter(
    array_map('trim', preg_split('/\n{2,}/', $reply)),
    function($s) { return $s !== ''; }
));
if (empty($msgs)) $msgs = [$reply];

// ===== ОТВЕТ =====
echo json_encode([
    'ok' => true,
    'messages' => $msgs,
    'quick_replies' => $buttons,
    'lead' => $lead,
], JSON_UNESCAPED_UNICODE);
