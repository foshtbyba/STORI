function isValidBGPhone($phone) {
    $clean = preg_replace('/[\s\-\(\)\.]+/', '', $phone);
    if (preg_match('/^(\+?359|00359)\d{8,9}$/', $clean)) return true;
    if (preg_match('/^0[1-9]\d{7,8}$/', $clean)) return true;
    return false;
}

function extractPhone($text) {
    $clean = preg_replace('/[\s\-\(\)\.]+/', '', $text);
    if (preg_match('/(\+?359\d{8,9}|00359\d{8,9}|0[1-9]\d{7,8})/', $clean, $m)) {
        return $m[1];
    }
    return $clean;
}

function findNameInHistory($history) {
    $expectName = false;
    foreach ($history as $msg) {
        if ($expectName && $msg['role'] === 'user') {
            $name = trim($msg['content']);
            if (mb_strlen($name) >= 2 && mb_strlen($name) < 50
                && !preg_match('/^\d|^0[1-9]|^\+?359/u', $name)
                && !preg_match('/\?|какв|колко|защо|състав|цена|помага|действа|доставка|какой|сколько|состав|почему|что\b/iu', $name)
                && mb_substr_count($name, ' ') <= 3) {
                return mb_convert_case($name, MB_CASE_TITLE, 'UTF-8');
            }
            $expectName = false;
        }
        if ($msg['role'] === 'assistant') {
            $c = $msg['content'];
            if (mb_strpos($c, 'Как се казвате') !== false
             || mb_strpos($c, 'как се казвате') !== false
             || mb_strpos($c, 'Нека ви запиша') !== false) {
                $expectName = true;
            } else {
                $expectName = false;
            }
        }
    }
    return 'Пациент';
}

