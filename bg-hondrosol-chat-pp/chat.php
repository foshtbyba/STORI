function findNameInHistory($history) {
    $expectName = false;
    $foundName = null;
    foreach ($history as $msg) {
        if ($expectName && $msg['role'] === 'user') {
            $name = trim($msg['content']);
            if (looksLikeName($name)) {
                $foundName = mb_convert_case($name, MB_CASE_TITLE, 'UTF-8');
            }
            $expectName = false;
        }
        if ($msg['role'] === 'assistant') {
            $c = $msg['content'];
            $asksName = (mb_strpos($c, 'Как се казвате') !== false
             || mb_strpos($c, 'как се казвате') !== false
             || mb_strpos($c, 'Как ви е името') !== false
             || mb_strpos($c, 'как ви е името') !== false
             || mb_strpos($c, 'Нека ви запиша') !== false);
            $qCount = mb_substr_count($c, '?');
            if ($asksName && $qCount <= 1) {
                $expectName = true;
            } else {
                $expectName = false;
            }
            if (preg_match('/Приятно ми е,\s*([^!.]+)/u', $c, $m)) {
                $extracted = trim($m[1]);
                if (looksLikeName($extracted)) {
                    $foundName = mb_convert_case($extracted, MB_CASE_TITLE, 'UTF-8');
                }
            }
        }
    }
    return $foundName ?: 'Пациент';
}

